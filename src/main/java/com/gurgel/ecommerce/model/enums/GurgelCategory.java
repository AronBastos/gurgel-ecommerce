/**
 * Categorias dos veículos da Gurgel Motores, montadora brasileira ativa
 * entre 1969 e 1996.
 */
public enum GurgelCategory {
    CLASSIC,      // BR-800, Supermini
    SPORTS,       // Modelos esportivos
    UTILITY,      // Xavante, Tocantins
    COLLECTOR,    // Modelos raros de colecionador
    HISTORICAL,   // Modelos com valor histórico
    PROTOTYPE,    // Modelos experimentais
    ELECTRIC,     // Itaipu (elétrico)
    PICKUP,       // Tocantins
    OFF_ROAD      // Xavante 4x4
}
